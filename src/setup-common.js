// Interactive setup: asks a few questions and writes a private .env file (mode 0600).
// Answers to secret questions are not echoed when setup runs in a terminal.
const fs = require('node:fs');
const readline = require('node:readline');
const { Writable } = require('node:stream');
const F = require('./files');
const { quoteEnvValue } = require('./env');

