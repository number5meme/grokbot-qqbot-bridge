function normalizeBool(key, v, dflt) {
  const s = String(v || '').trim().toLowerCase() || dflt;
  const yes = ['y', 'yes', 'on', 'true', '1'].includes(s);
  const no = ['n', 'no', 'off', 'false', '0'].includes(s);
  if (!yes && !no) return null;
  if (key === 'OWNER_PROTECTION') return yes ? 'on' : 'off';
  return yes ? 'true' : 'false';
}

/** Render answers as .env text. */
function renderEnv(answers, questions) {
  const lines = ['# Generated by setup. Keep this file private (it may contain secrets).'];
  for (const q of questions) {
    const v = answers[q.key];
    if (v === undefined || v === '') continue;
    lines.push(`${q.key}=${quoteEnvValue(String(v))}`);
  }
  return lines.join('\n') + '\n';
}

/**
 * Line reader with optional hidden input.
 * terminal=true: readline handles echo itself (raw mode), so muting its output hides what is typed.
 * terminal=false (piped input): nothing is echoed by the terminal; lines are read as they come.
 * Lines are queued, so answers piped in all at once are not lost.
 */
function createAsker({ input, output, terminal }) {
  let muted = false;
  const echo = new Writable({ write(chunk, enc, cb) { if (!muted) output.write(chunk); cb(); } });
  const rl = readline.createInterface({ input, output: terminal ? echo : undefined, terminal: Boolean(terminal) });
  const queue = []; const waiting = []; let closed = false;
  rl.on('line', (l) => { if (waiting.length) waiting.shift().resolve(l); else queue.push(l); });
  rl.on('close', () => {
    closed = true;
    while (waiting.length) waiting.shift().reject(new Error('setup aborted: input ended before all questions were answered'));
  });
  rl.on('SIGINT', () => { muted = false; output.write('\n'); rl.close(); });
  const ask = (prompt, { secret = false } = {}) => {
    if (terminal && !secret) { rl.setPrompt(prompt); rl.prompt(); } // readline redraws the prompt on edits
    else { if (terminal) rl.setPrompt(''); output.write(prompt); }
    if (queue.length) return Promise.resolve(queue.shift());
    if (closed) return Promise.reject(new Error('setup aborted: input ended before all questions were answered'));
    muted = Boolean(secret && terminal);
    return new Promise((resolve, reject) => waiting.push({ resolve, reject })).finally(() => {
      if (muted) { muted = false; output.write('\n'); }
    });
  };
  return { ask, close: () => rl.close() };
}

async function runSetup({ questions, file, input = process.stdin, output = process.stdout, terminal = Boolean(input.isTTY) }) {
  const asker = createAsker({ input, output, terminal });
  const answers = {};
  try {
    output.write(`This writes ${file}. Press Enter to accept a default.\n\n`);
    for (const q of questions) {
      if (q.when && !q.when(answers)) continue;
      output.write(`${q.key}: ${q.help}\n`);
      for (;;) {
        const raw = (await asker.ask(`  ${q.key}${q.dflt ? ` [${q.dflt}]` : ''}: `, { secret: q.secret })).trim();
        if (q.type === 'bool') {
          const v = normalizeBool(q.key, raw, q.dflt);
          if (v === null) { output.write('  please answer yes or no\n'); continue; }
          answers[q.key] = v; break;
        }
        if (!raw && q.required) { output.write('  this value is required\n'); continue; }
        answers[q.key] = raw || q.dflt || ''; break;
      }
      output.write('\n');
    }
  } finally { asker.close(); }
  const hadFile = fs.existsSync(file);
  if (hadFile) F.writeSecure(`${file}.bak`, fs.readFileSync(file)); // private copy (mode 600)
  F.writeSecure(file, renderEnv(answers, questions)); // atomic: a crash never leaves a truncated .env
  output.write(`Wrote ${file} (mode 600).${hadFile ? ` The previous file was kept as ${file}.bak.` : ''}\n`);
  return answers;
}

module.exports = { COMMON_QUESTIONS, renderEnv, normalizeBool, runSetup, createAsker };
